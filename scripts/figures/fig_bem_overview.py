# ------------------------------------------------------------------ IDF geometry and envelope U-values
def parse_idf(path):
    text = '\n'.join(line.split('!')[0] for line in open(path, encoding='latin-1').read().splitlines())
    objects = collections.defaultdict(list)
    for chunk in text.split(';'):
        fields = [f.strip() for f in chunk.split(',')]
        if fields[0]:
            objects[fields[0].upper()].append(fields[1:])
    return objects


def load_geometry(building):
    o = parse_idf(config.MODELS_DIR / f'{building}_bem_calibrated.idf')
    vertices = lambda values: np.array([float(x) for x in values]).reshape(-1, 3)
    surfaces = [dict(name=s[0], type=s[1], cons=s[2], zone=s[3], bc=s[5], v=vertices(s[11:])) for s in o['BUILDINGSURFACE:DETAILED']]
    fenestrations = [dict(name=s[0], cons=s[2], v=vertices(s[9:])) for s in o.get('FENESTRATIONSURFACE:DETAILED', [])]
    shades = [dict(group=s[0].split('-')[0], v=vertices(s[3:])) for s in o.get('SHADING:BUILDING:DETAILED', [])]
    return surfaces, fenestrations, shades


def u_values(building):
    """U-factor with film of each construction from the EnergyPlus envelope summary of the tuned model"""
    rows = list(csv.reader(open(config.CALIBRATION_RESULTS_DIR / 'simulation' / f'{building}_tunedTable.csv', encoding='latin-1')))
    values, section, header = collections.defaultdict(list), None, None
    for r in rows:
        if len(r) == 1 and r[0] in ('Opaque Exterior', 'Exterior Fenestration', 'Opaque Interior', 'Exterior Fenestration Shaded State'):
            section, header = r[0], None
            continue
        if section in ('Opaque Exterior', 'Exterior Fenestration') and len(r) > 3:
            if r[2] == 'Construction':
                header = r
                continue
            if header and r[1] and r[1] not in ('Total or Average', 'North Total or Average', 'Non-North Total or Average'):
                column = 'U-Factor with Film [W/m2-K]' if section == 'Opaque Exterior' else 'Glass U-Factor [W/m2-K]'
                try:
                    values[r[2].upper()].append(float(r[header.index(column)]))
                except (ValueError, IndexError):
                    pass
    return {k: float(np.median(v)) for k, v in values.items()}


def construction_category(name):
    if name.startswith('WL_POLIMI-LC_EW'):
        return f"External wall {name.split('_')[-1]}"
    if name == 'WL_POLIMI-LC_FC300':
        return 'Concrete wall FC300 (uninsulated)'
    if name.startswith('WL_POLIMI-LC_FC300'):
        return 'Concrete wall FC300-2/-3 (insulated)'
    if name.startswith('WL_POLIMI-LC_IW'):
        return 'Partition types IW (exposed)'
    if name.startswith('RF_'):
        return 'Roof'
    if 'GroundFloor' in name or 'Ground Slab' in name:
        return 'Ground floor'
    if 'InternalFloor' in name:
        return 'Floor over outdoor air'
    if name.startswith('curtainWall'):
        return 'Curtain-wall glazing'
    if name.startswith('window'):
        return 'Window glazing'
    if name.startswith('Generic Double Pane'):
        return 'Curtain wall, HB default glazing'
    return name


# ------------------------------------------------------------------ axonometric projection
def normal(v):
    n = np.zeros(3)
    for i in range(len(v)):
        n += np.cross(v[i], v[(i + 1) % len(v)])
    return n


def area(v):
    return np.linalg.norm(normal(v)) / 2


def view(azimuth, elevation):
    azimuth, elevation = np.radians(azimuth), np.radians(elevation)
    d = np.array([np.cos(elevation) * np.cos(azimuth), np.cos(elevation) * np.sin(azimuth), np.sin(elevation)])
    r = np.cross([0, 0, 1], d)
    r /= np.linalg.norm(r)
    return d, r, np.cross(d, r)


def project(v, V):
    return np.c_[v @ V[1], v @ V[2]]


def draw(ax, polygons, V, cull=True, lw=0.12):
    items = []
    for v, colour, can_cull in polygons:
        if cull and can_cull and np.dot(normal(v), V[0]) <= 1e-6:
            continue
        items.append((np.mean(v, axis=0) @ V[0], project(v, V), colour))
    items.sort(key=lambda item: item[0])
    ax.add_collection(PolyCollection([p for _, p, _ in items], facecolors=[c for _, _, c in items], edgecolors='#3a3a3a', linewidths=lw, zorder=1))
    return np.vstack([p for _, p, _ in items])


def finish(ax, points, V, length=10, plan=False, pad=2, north_position=(0.20, 0.93), top=0.16):
    low, high = points.min(0) - pad, points.max(0) + pad
    high[1] += top * (high[1] - low[1])
    ax.set_xlim(low[0], high[0]); ax.set_ylim(low[1], high[1]); ax.set_aspect('equal', adjustable='datalim'); ax.axis('off')
    fig.canvas.draw()
    a = np.radians(NORTH_AXIS)
    north = project(np.array([[0, 0, 0], [-np.sin(a), np.cos(a), 0.0]]), V)
    north = (north[1] - north[0]) / np.linalg.norm(north[1] - north[0])
    (x0, y0), arrow = north_position, 0.08
    ax.annotate('', xy=(x0 + north[0] * arrow, y0 + north[1] * arrow), xytext=(x0, y0), xycoords='axes fraction',
                arrowprops=dict(arrowstyle='-|>,head_length=0.45,head_width=0.22', color='black', lw=0.9), zorder=30)
    ax.text(x0 + north[0] * (arrow + 0.05), y0 + north[1] * (arrow + 0.05), 'N', transform=ax.transAxes, ha='center', va='center',
            fontsize=6.5, fontweight='bold')
    segment = project(np.array([[0, 0, 0], [length, 0, 0]]), V)
    x_min, x_max = ax.get_xlim()
    fraction = np.linalg.norm(segment[1] - segment[0]) / (x_max - x_min)
    xs, ys = 0.62, 0.97
    ax.plot([xs, xs + fraction], [ys, ys], transform=ax.transAxes, color='black', lw=2.2, solid_capstyle='butt', zorder=29)
    ax.plot([xs + fraction / 2, xs + fraction], [ys, ys], transform=ax.transAxes, color='white', lw=1.4, solid_capstyle='butt', zorder=31)
    ax.text(xs + fraction + 0.015, ys, f'{length} m' + ('' if plan else ' (along x)'), transform=ax.transAxes, fontsize=5.5, va='center', ha='left')


def title(ax, text):
    ax.set_title(text, loc='left', fontsize=6.6, pad=1)


# ------------------------------------------------------------------ data
zone_uses = pd.read_excel(config.DATA_DIR / 'mapping' / 'bim2bem_mapping_topologic_ifc_honeybee_energyplus.xlsx', sheet_name='T7_Zones', header=0)
DATA = {}
for building in ('building09', 'building10'):
    surfaces, fenestrations, shades = load_geometry(building)
    z = zone_uses[zone_uses.iloc[:, 0] == f'B{building[-2:]}']
    DATA[building] = dict(S=surfaces, F=fenestrations, SH=shades, use={zone.lower(): use.split(' – ')[0] for zone, use in zip(z.iloc[:, 1], z.iloc[:, 2])},
                          EXT=[s for s in surfaces if s['bc'] in ('Outdoors', 'Ground', 'Adiabatic')], U=u_values(building))

# ------------------------------------------------------------------ figure
fig = plt.figure(figsize=(17.4 * CM, 25.6 * CM))
ROWS_Y = {'zones': 0.8008, 'bc': 0.582, 'cons': 0.3438}
ROW_HEIGHT = {'zones': 0.1602, 'bc': 0.1406, 'cons': 0.1641}
COLS_X = {'building10': 0.005, 'building09': 0.505}
for building, x in COLS_X.items():
    fig.text(x + 0.005, 0.985, f'Building {building[-2:]}', fontsize=8.5, fontweight='bold', color=NAVY, va='top')
letters = iter('abcdefg')
panels = {(row, b): fig.add_axes([COLS_X[b], ROWS_Y[row], 0.49, ROW_HEIGHT[row]]) for row in ROWS_Y for b in ('building10', 'building09')}


def legend_at(y, items, ncol):
    fig.legend(handles=[Patch(fc=c, ec='#3a3a3a', lw=0.3, label=l) for l, c in items], loc='upper left', bbox_to_anchor=(0.01, y), ncol=ncol,
               frameon=False, fontsize=5.7, handlelength=1.2, handleheight=0.9, columnspacing=1.0, labelspacing=0.28)


# (a, b) thermal zones on exploded floor plates
for building in ('building10', 'building09'):
    ax, d, V, explosion = panels[('zones', building)], DATA[building], view(*VIEW[building][:2]), VIEW[building][2]
    levels = []
    for z in sorted({round(s['v'][:, 2].mean(), 1) for s in d['S'] if s['type'].lower() == 'floor'}):
        if not levels or z - levels[-1] > 1.5:
            levels.append(z)
    ground = int(np.argmin([abs(level) for level in levels]))
    polygons, zones_per_level = [], collections.defaultdict(set)
    for s in d['S']:
        if s['type'].lower() != 'floor':
            continue
        k = int(np.argmin([abs(s['v'][:, 2].mean() - level) for level in levels]))
        v = s['v'].copy(); v[:, 2] += k * explosion
        polygons.append((v, USE_COLOURS.get(d['use'].get(s['zone'].lower(), ''), '#ffffff'), False))
        zones_per_level[k].add(s['zone'].lower())
    points = draw(ax, polygons, V, cull=False, lw=0.18)
    x_label = points[:, 0].min() - 2
    for k in range(len(levels)):
        q = project(np.vstack([p[0] for p in polygons if abs(p[0][:, 2].mean() - (levels[k] + k * explosion)) < 1]), V)
        ax.text(x_label, q[:, 1].mean(), f'Level {k - ground}'.replace('-', '−') + f'\n{len(zones_per_level[k])} zones',
                ha='right', va='center', fontsize=5.5, color=NAVY)
    points = np.vstack([points, [points[:, 0].min() - 17, points[:, 1].mean()]])
    conditioned = sum(1 for use in d['use'].values() if not use.startswith('Unconditioned'))
    finish(ax, points, V, pad=1)
    title(ax, f"({next(letters)}) Thermal zones by use: {len(d['use'])} zones ({conditioned} conditioned)")
counts = {b: collections.Counter(DATA[b]['use'].values()) for b in DATA}
legend_at(ROWS_Y['zones'] - 0.002, [(f"{u} (B10: {counts['building10'][u]}, B09: {counts['building09'][u]})", c)
                                    for u, c in USE_COLOURS.items() if counts['building09'][u] or counts['building10'][u]], 2)

# (c, d) outside boundary conditions
boundary_stats = {}
for building in ('building10', 'building09'):
    ax, d, V = panels[('bc', building)], DATA[building], view(*VIEW[building][:2])
    finish(ax, draw(ax, [(s['v'], BOUNDARY_COLOURS[s['bc']], True) for s in d['EXT']], V), V)
    n, a = collections.Counter(s['bc'] for s in d['EXT']), collections.Counter()
    for s in d['EXT']:
        a[s['bc']] += area(s['v'])
    boundary_stats[building] = (n, a)
    title(ax, f'({next(letters)}) Outside boundary conditions')
legend_at(ROWS_Y['bc'] - 0.002, [(f"{k} (B10: {boundary_stats['building10'][0][k]} surfaces, {boundary_stats['building10'][1][k]:,.0f} m²; "
                                  f"B09: {boundary_stats['building09'][0][k]} surfaces, {boundary_stats['building09'][1][k]:,.0f} m²)", c)
                                 for k, c in BOUNDARY_COLOURS.items()], 1)

# (e, f) constructions
areas, u_by_category = {b: collections.Counter() for b in DATA}, collections.defaultdict(set)
for building in ('building10', 'building09'):
    ax, d, V = panels[('cons', building)], DATA[building], view(*VIEW[building][:2])
    polygons = [(s['v'], CONSTRUCTION_COLOURS.get(construction_category(s['cons']), '#ffffff'), True) for s in d['EXT']]
    for f in d['F']:
        n = normal(f['v']); n = n / np.linalg.norm(n)
        polygons.append((f['v'] + n * 0.05, CONSTRUCTION_COLOURS.get(construction_category(f['cons']), '#ffffff'), True))
    finish(ax, draw(ax, polygons, V), V)
    title(ax, f'({next(letters)}) Construction types (opaque envelope and glazing)')
    for s in d['EXT']:
        areas[building][construction_category(s['cons'])] += area(s['v'])
        if s['cons'].upper() in d['U'] and s['bc'] != 'Adiabatic':
            u_by_category[construction_category(s['cons'])].add(round(d['U'][s['cons'].upper()], 2))
    for f in d['F']:
        areas[building][construction_category(f['cons'])] += area(f['v'])
        if f['cons'].upper() in d['U']:
            u_by_category[construction_category(f['cons'])].add(round(d['U'][f['cons'].upper()], 2))


def u_text(category):
    u = sorted(u_by_category.get(category, []))
    if not u:
        return 'U n/a'
    return f'U {u[0]:.2f}' if len(u) == 1 or u[-1] - u[0] < 0.015 else f'U {u[0]:.2f}–{u[-1]:.2f}'


legend_at(ROWS_Y['cons'] - 0.002, [(f"{k}: {u_text(k)} W/m²K (B10 {areas['building10'][k]:,.0f} m², B09 {areas['building09'][k]:,.0f} m²)", c)
                                   for k, c in CONSTRUCTION_COLOURS.items() if areas['building09'][k] or areas['building10'][k]], 2)

# (g) site plan
ax = fig.add_axes([0.005, 0.0156, 0.49, 0.2187])
plan_view = (np.array([0, 0, 1.0]), np.array([1.0, 0, 0]), np.array([0, 1.0, 0]))
shades09, shades10 = DATA['building09']['SH'], DATA['building10']['SH']
is_roof = lambda s: normal(s['v'])[2] > 0.5 * np.linalg.norm(normal(s['v']))
polygons = [(s['v'], {'shade0': '#fdae6b', 'shade1': '#bdbdbd'}[s['group']], False) for s in shades09 if s['group'] in ('shade0', 'shade1')]
polygons += [(s['v'], '#fdae6b', False) for s in shades10 if s['group'] == 'shade0']
polygons += [(s['v'], '#4c78a8', False) for s in DATA['building09']['S'] if s['bc'] != 'Surface' and is_roof(s)]
polygons += [(s['v'], '#e45756', False) for s in DATA['building10']['S'] if s['bc'] != 'Surface' and is_roof(s)]
finish(ax, draw(ax, polygons, plan_view, cull=False, lw=0.18), plan_view, length=20, plan=True, pad=1, north_position=(0.97, 0.80), top=0.10)
title(ax, f'({next(letters)}) Site plan: modelled buildings and external shading')
balconies = sum(1 for s in shades09 if s['group'] == 'shade0') + sum(1 for s in shades10 if s['group'] == 'shade0')
context = sum(1 for s in shades09 if s['group'] == 'shade1')
ax.legend(handles=[Patch(fc=c, ec='#3a3a3a', lw=0.3, label=l) for l, c in
                   [('Building 10 (roofs)', '#e45756'), ('Building 09 (roofs)', '#4c78a8'),
                    (f'Balconies / overhangs ({balconies} surfaces)', '#fdae6b'), (f'Context buildings ({context} surfaces)', '#bdbdbd')]],
          loc='upper left', bbox_to_anchor=(1.03, 0.95), frameon=False, fontsize=5.8, handlelength=1.2, handleheight=0.9)
fig.text(0.53, 0.03, 'Axonometric views: scale bar valid along the building x axis.\n'
         'North arrows indicate true north (building north axis 45°).\n'
         'U = thermal transmittance including surface films (EnergyPlus).\n'
         'Zones spanning several levels are counted at each level.', fontsize=5.6, color='#444444', va='bottom')
save(fig, 'bem_overview')
